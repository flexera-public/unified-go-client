// These predate schema-derived dispatch and remain supported for compatibility.
var tableKindAliases = map[string]string{
	"iam:event-collection":                "IamEventCollection",
	"iam:customization-type-list":         "IamCustomizationTypeList",
	"iam:customization-list":              "IamCustomizationList",
	"policy:published-template-list":      "PolicyPublishedTemplateList",
	"policy:custom-catalog-template-list": "PolicyCustomCatalogTemplateList",
}

func renderTableFile(packageName string, models, renderer *ast.File, aliases map[string]string) ([]byte, error) {
	supported, err := tableResponseTypes(renderer)
	if err != nil {
		return nil, err
	}
	kinds, err := tableResponseKinds(models, supported, aliases)
	if err != nil {
		return nil, err
	}
	keys := make([]string, 0, len(kinds))
	for kind := range kinds {
		keys = append(keys, kind)
	}
	sort.Strings(keys)
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by split-client from WriteTable and model kind enums; DO NOT EDIT.\n\npackage %s\n\n", packageName)
	out.WriteString("func newTableResponse(kind string) any {\n switch kind {\n")
	for _, kind := range keys {
		fmt.Fprintf(&out, "case %q:\n return &%s{}\n", kind, kinds[kind])
	}
	out.WriteString("default:\n return nil\n }\n}\n")
	return format.Source(out.Bytes())
}

func tableResponseTypes(renderer *ast.File) (map[string]bool, error) {
	for _, decl := range renderer.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv != nil || fn.Name.Name != "WriteTable" || fn.Body == nil {
			continue
		}
		types := map[string]bool{}
		for _, stmt := range fn.Body.List {
			sw, ok := stmt.(*ast.TypeSwitchStmt)
			if !ok {
				continue
			}
			for _, clause := range sw.Body.List {
				for _, expr := range clause.(*ast.CaseClause).List {
					if ptr, ok := expr.(*ast.StarExpr); ok {
						if name, ok := ptr.X.(*ast.Ident); ok {
							types[name.Name] = true
						}
					}
				}
			}
			return types, nil
		}
		return nil, fmt.Errorf("WriteTable has no response type switch")
	}
	return nil, fmt.Errorf("WriteTable declaration not found")
}

func tableResponseKinds(models *ast.File, supported map[string]bool, aliases map[string]string) (map[string]string, error) {
	types := map[string]ast.Expr{}
	enums := map[string][]string{}
	for _, decl := range models.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		var constType ast.Expr
		var constValues []ast.Expr
		for _, spec := range gen.Specs {
			switch spec := spec.(type) {
			case *ast.TypeSpec:
				types[spec.Name.Name] = spec.Type
			case *ast.ValueSpec:
				if gen.Tok != token.CONST {
					continue
				}
				if len(spec.Values) > 0 {
					constType, constValues = spec.Type, spec.Values
				}
				name, ok := constType.(*ast.Ident)
				if !ok {
					continue
				}
				for _, value := range constValues {
					if lit, ok := value.(*ast.BasicLit); ok && lit.Kind == token.STRING {
						text, err := strconv.Unquote(lit.Value)
						if err != nil {
							return nil, err
						}
						enums[name.Name] = append(enums[name.Name], text)
					}
				}
			}
		}
	}
	owners := map[string]map[string]bool{}
	for name := range supported {
		model, exists := types[name]
		if !exists {
			return nil, fmt.Errorf("WriteTable response type %s is absent from generated models", name)
		}
		st, ok := model.(*ast.StructType)
		if !ok {
			continue // Bare arrays have no envelope discriminator.
		}
		for _, field := range st.Fields.List {
			if field.Tag == nil {
				continue
			}
			tag, err := strconv.Unquote(field.Tag.Value)
			if err != nil {
				return nil, err
			}
			if strings.Split(reflect.StructTag(tag).Get("json"), ",")[0] != "kind" {
				continue
			}
			expr := field.Type
			if ptr, ok := expr.(*ast.StarExpr); ok {
				expr = ptr.X
			}
			enum, ok := expr.(*ast.Ident)
			if !ok {
				continue
			}
			for _, kind := range enums[enum.Name] {
				if owners[kind] == nil {
					owners[kind] = map[string]bool{}
				}
				owners[kind][name] = true
			}
		}
	}
	result := map[string]string{}
	for kind, candidates := range owners {
		if len(candidates) == 1 {
			for name := range candidates {
				result[kind] = name
			}
		}
	}
	for kind, name := range aliases {
		if !supported[name] {
			continue
		}
		if candidates := owners[kind]; len(candidates) > 0 && (len(candidates) != 1 || !candidates[name]) {
			return nil, fmt.Errorf("table kind alias %q for %s conflicts with generated model kinds", kind, name)
		}
		result[kind] = name
	}
	return result, nil
}

func generateTableFile(opts options, packageName string) ([]byte, error) {
	renderer, err := parser.ParseFile(token.NewFileSet(), filepath.Join(opts.outputDir, "render_table.go"), nil, 0)
	if os.IsNotExist(err) {
		return nil, nil // Splitter fixtures and consumers need not supply table rendering.
	}
	if err != nil {
		return nil, fmt.Errorf("parse table renderer: %w", err)
	}
	models, err := parser.ParseFile(token.NewFileSet(), opts.input, nil, 0)
	if err != nil {
		return nil, fmt.Errorf("parse table models: %w", err)
	}
	return renderTableFile(packageName, models, renderer, tableKindAliases)
}
